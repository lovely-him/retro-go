// Goodix GT9xx 电容触摸控制器驱动
//
// 本板 10.1" 屏的触摸芯片实测自报 "927"(产品 ID 0x8140 读到 39 32 37), 是 GT927;
// 厂商 BSP 按 GT911 处理同一块板。文件与宏名沿用 gt911, 因为 GT9xx 家族共用这套
// 寄存器映射, 厂商的 esp_lcd_touch_gt911 也是一个驱动覆盖全家。详见 gt911.c。
//
// 触摸与背光控制器 0x45、ES8311 0x18 共用同一条 I2C 总线(SDA=GPIO7, SCL=GPIO8),
// 只是地址不同(0x5D)。GT9xx 的寄存器地址是 16 位、上线时高字节先发, 数据是小端,
// 所以走 rg_i2c_read_reg16/write_reg16 而不是普通的 rg_i2c_read。
//
// 只读不写: 本驱动不碰 0x8040(命令寄存器), 也不做硬件复位。原因见 gt911.c 里的
// 说明 —— 本板的 INT/RST 都是 NC, 写 0x05 进睡眠之后再也没有办法唤醒。
//
// 只出现纯 C 类型。目前本文件只被 gt911.c 和 rg_input.c 两个 .c 包含, 所以并不在
// rg_system.h 的包含链上, BIT8 那类宏冲突(见 rg_i2c.h 顶部说明)此刻并不会发生。
// 但这条纪律要保持: 一旦被哪个 .h 包含进去, 它就会流进每一个核心的每一个编译单元,
// 而任何 IDF 驱动头文件都会带进 esp_bit_defs.h 的 BIT0..BIT31 对象宏, 与 snes9x
// cpuops.c 里定义成函数的 BIT8()/BIT16() 冲突。

#pragma once

#include <stdbool.h>
#include <stdint.h>

// GT9xx 最多同时上报 5 个点
#define RG_TOUCH_MAX_POINTS     5

typedef struct
{
    int x;
    int y;
    uint8_t id; // 触点编号, 由控制器分配, 抬起后会被复用
} rg_touch_point_t;

// 探测并初始化。成功返回 true; 失败(总线上没有 GT911)返回 false, 调用方照常继续,
// 退化为无触摸输入。
bool rg_gt911_init(void);

// 取当前触点。返回实际写入 points 的点数(0 = 没有手指按下), 出错返回 -1。
//
// 坐标是【面板坐标】原值, 不做任何方向翻转或缩放。2026-09-25 四角实测确认了这套
// 坐标系, 与厂商 BSP 把 swap_xy / mirror_x / mirror_y 全设 0 一致:
//
//     原点在左上角; X 向右, 量程 0..800; Y 向下, 量程 0..1280; 不交换、不镜像
//     左上 (33,27)   右上 (775,16)   右下 (791,1255)   左下 (28,1277) / (5,1276)
//
// 实测极值距 0 和满量程都还差十几到几十像素, 那是手指按不到物理边缘, 属正常, 不是
// 量程偏差 —— 芯片配置里读出的分辨率正好是 800x1280。
//
// panel -> logical 的换算不属于本驱动: 面板布局(内容 640x480 放在偏移 (80,0) 处)是
// 显示驱动的知识, 触摸驱动只报告控制器给出的原始数字。
int rg_gt911_read(rg_touch_point_t *points, int max_points);
